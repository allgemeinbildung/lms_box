// Writes dashboard/modules/mindmapUnits.js: the units of the Lehrmittel that the mindmap
// print view offers (CONTRACT.md, «Mindmap print view»). Page names only, no data.
//
//   node scripts/mindmap-units.mjs --vault ../../vault/ABUlehrmittel
//
// A unit is a note `X.Y ….md` directly in a chapter folder of ABUlehrmittel/. Its id is the
// Publish page without the leading slash: `ABUlehrmittel/<folder>/<note>`.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, resolve, basename, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const args = process.argv.slice(2);
const at = args.indexOf('--vault');
if (at < 0 || !args[at + 1]) {
    console.error('Usage: node scripts/mindmap-units.mjs --vault <path to vault/ABUlehrmittel>');
    process.exit(1);
}
const vault = resolve(args[at + 1]);
const top = basename(vault);                       // "ABUlehrmittel"
const UNIT = /^\d+\.\d+ .+\.md$/;
const byNumber = (a, b) => a.localeCompare(b, 'de', { numeric: true });

const units = [];
for (const folder of readdirSync(vault).sort(byNumber)) {
    const dir = join(vault, folder);
    if (!/^\d+ /.test(folder) || !statSync(dir).isDirectory()) continue;
    for (const file of readdirSync(dir).sort(byNumber)) {
        if (!UNIT.test(file) || / - Kopie|-LYOBBW/.test(file)) continue;
        const note = file.slice(0, -3);
        units.push({ folder, note, unit: `${top}/${folder}/${note}` });
    }
}

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../dashboard/modules/mindmapUnits.js');
writeFileSync(out, `//
//  dashboard/modules/mindmapUnits.js — GENERATED by backend/scripts/mindmap-units.mjs. Do not edit.
//  The units of the Lehrmittel for the mindmap print view (CONTRACT.md, «Mindmap print view»).
//
export const UNITS = ${JSON.stringify(units, null, 4)};
`, 'utf8');
console.log(`${units.length} units -> ${out}`);
